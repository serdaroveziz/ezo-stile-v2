export function detectDefaultLanguage() {
  if (typeof window === 'undefined') return 'tr';
  const saved = localStorage.getItem('ezo_lang');
  if (saved && ['tr', 'en', 'ru', 'ar', 'tk', 'fa'].includes(saved)) return saved;
  
  const navLang = (navigator.language || 'tr').toLowerCase();
  if (navLang.startsWith('en')) return 'en';
  if (navLang.startsWith('ru')) return 'ru';
  if (navLang.startsWith('ar')) return 'ar';
  if (navLang.startsWith('tk') || navLang.startsWith('tm')) return 'tk';
  if (navLang.startsWith('fa')) return 'fa';
  return 'tr';
}

export function isRtl(lang) {
  return lang === 'ar' || lang === 'fa';
}

export function applyDocumentLanguage(lang) {
  const safeLang = SUPPORTED_LANGUAGES.some(item => item.code === lang) ? lang : 'tr';
  if (typeof document !== 'undefined') {
    document.documentElement.lang = safeLang;
    document.documentElement.dir = isRtl(safeLang) ? 'rtl' : 'ltr';
  }
  return safeLang;
}

