export function t(key, lang = null, params = null) {
  const documentLang = typeof document !== 'undefined' && document.documentElement && document.documentElement.lang;
  const activeLang = lang || documentLang || detectDefaultLanguage();
  const dict = DICTIONARY[activeLang] || DICTIONARY.tr;
  const value = dict[key] || DICTIONARY.tr[key] || key;
  if (!params || typeof value !== 'string') return value;
  return value.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}

